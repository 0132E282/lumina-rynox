import { router } from '@inertiajs/react';
import { invalidateAiChatCache } from '@/lib/ai-chat-cache';
import { useState } from 'react';
import InputError from '@/components/input-error';
import { Button } from '@/components/ui/button';
import {
    Dialog,
    DialogContent,
    DialogDescription,
    DialogFooter,
    DialogHeader,
    DialogTitle,
} from '@/components/ui/dialog';
import { VendorBadge } from '@/components/ai-chat/vendor-badge';
import {
    CliLogin,
    cliVendorOf,
    useCliLogin,
} from '@/components/integrations/cli-login';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import {
    Select,
    SelectContent,
    SelectItem,
    SelectTrigger,
    SelectValue,
} from '@/components/ui/select';
import {
    store,
    update,
} from '@/actions/App/Http/Controllers/AiAccountController';
import type { AiAccountSummary, AiOptions } from '@/types';

type Errors = Record<string, string | undefined>;

/**
 * Add or edit ONE AI account. The token is write-only: while editing it starts empty and a blank value keeps the stored one.
 * The name is generated by the server for a new account, and the purposes are not edited here: a new account serves all of them, an edit keeps the saved ones.
 */
export function AiAccountDialog({
    account,
    options,
    onClose,
}: {
    account: AiAccountSummary | null;
    options: AiOptions;
    onClose: () => void;
}) {
    const [vendor, setVendor] = useState(account?.vendor ?? 'anthropic');
    const [authType, setAuthType] = useState(account?.auth_type ?? 'api_token');
    const [token, setToken] = useState('');
    const [errors, setErrors] = useState<Errors>({});
    const [submitting, setSubmitting] = useState(false);

    // * "Đăng nhập" replaces "Lưu" for a CLI account whose CLI has a login flow here (Claude, OpenAI/Codex).
    const cliVendor = authType === 'session_token' ? cliVendorOf(vendor) : null;
    const cli = useCliLogin(cliVendor);
    const loggingIn = cli.state === 'waiting';

    // * Already signed in: just save. Otherwise sign in through the CLI first and save once it reports a user.
    const primary = async () => {
        if (cliVendor !== null && cli.state !== 'in' && !(await cli.login())) {
            return;
        }

        submit();
    };

    const submit = () => {
        const data = {
            vendor,
            auth_type: authType,
            token,
        };
        const visitOptions = {
            preserveScroll: true,
            onSuccess: () => {
                invalidateAiChatCache('usage');
                onClose();
            },
            onError: (caught: Errors) => setErrors(caught),
            onFinish: () => {
                // * The token is never kept in state once the request settles.
                setToken('');
                setSubmitting(false);
            },
        };

        setSubmitting(true);
        setErrors({});

        if (account === null) {
            router.post(store.url(), data, visitOptions);
        } else {
            router.put(update.url(account.id), data, visitOptions);
        }
    };

    const idPrefix = `ai-account-${account?.id ?? 'new'}`;

    return (
        <Dialog open onOpenChange={(open) => !open && onClose()}>
            <DialogContent className="max-h-[90vh] overflow-y-auto sm:max-w-lg">
                <DialogHeader>
                    <DialogTitle className="flex items-center gap-2">
                        <VendorBadge
                            vendorKey={vendor}
                            fallback={vendor}
                            className="size-6"
                        />
                        {account === null
                            ? 'Thêm tài khoản AI'
                            : 'Sửa tài khoản AI'}
                    </DialogTitle>
                    <DialogDescription>
                        Token được lưu mã hoá và không hiển thị lại. AI chỉ tự
                        gửi tin cho khách khi bạn bật công tắc “Trả lời tự
                        động”.
                    </DialogDescription>
                </DialogHeader>

                <div className="grid gap-4">
                    <div className="grid gap-4 sm:grid-cols-2">
                        <div className="grid gap-2">
                            <Label htmlFor={`${idPrefix}-vendor`}>
                                Nhà cung cấp
                            </Label>
                            <Select value={vendor} onValueChange={setVendor}>
                                <SelectTrigger
                                    id={`${idPrefix}-vendor`}
                                    className="w-full"
                                >
                                    <SelectValue />
                                </SelectTrigger>
                                <SelectContent>
                                    {options.vendors.map((option) => (
                                        <SelectItem
                                            key={option.value}
                                            value={option.value}
                                        >
                                            {option.label}
                                        </SelectItem>
                                    ))}
                                </SelectContent>
                            </Select>
                            <InputError message={errors.vendor} />
                        </div>
                        <div className="grid gap-2">
                            <Label htmlFor={`${idPrefix}-auth`}>
                                Loại token
                            </Label>
                            <Select
                                value={authType}
                                onValueChange={(value) =>
                                    setAuthType(
                                        value as AiAccountSummary['auth_type'],
                                    )
                                }
                            >
                                <SelectTrigger
                                    id={`${idPrefix}-auth`}
                                    className="w-full"
                                >
                                    <SelectValue />
                                </SelectTrigger>
                                <SelectContent>
                                    {options.auth_types.map((option) => (
                                        <SelectItem
                                            key={option.value}
                                            value={option.value}
                                        >
                                            {option.label}
                                        </SelectItem>
                                    ))}
                                </SelectContent>
                            </Select>
                            <InputError message={errors.auth_type} />
                        </div>
                    </div>

                    {cliVendor !== null ? (
                        <CliLogin
                            vendor={cliVendor}
                            state={cli.state}
                            reason={cli.reason}
                        />
                    ) : (
                        <div className="grid gap-2">
                            <Label htmlFor={`${idPrefix}-token`}>Token</Label>
                            <Input
                                id={`${idPrefix}-token`}
                                type="password"
                                autoComplete="off"
                                value={token}
                                placeholder={
                                    account?.token_mask ??
                                    'Dán API token hoặc session token'
                                }
                                onChange={(event) =>
                                    setToken(event.target.value)
                                }
                                aria-invalid={!!errors.token}
                            />
                            {account !== null && (
                                <p className="text-xs text-muted-foreground">
                                    Để trống để giữ token đang lưu.
                                </p>
                            )}
                            <InputError message={errors.token} />
                        </div>
                    )}
                </div>

                <DialogFooter>
                    <Button
                        type="button"
                        variant="outline"
                        onClick={onClose}
                        disabled={submitting}
                    >
                        Huỷ
                    </Button>
                    {cliVendor !== null && cli.state === 'in' && (
                        <Button
                            type="button"
                            variant="outline"
                            onClick={() => void cli.login()}
                            disabled={submitting}
                        >
                            Đăng nhập lại
                        </Button>
                    )}
                    <Button
                        type="button"
                        onClick={() => void primary()}
                        disabled={
                            submitting ||
                            loggingIn ||
                            (cliVendor !== null && cli.state === 'checking')
                        }
                    >
                        {loggingIn
                            ? 'Đang đăng nhập…'
                            : cliVendor !== null && cli.state !== 'in'
                              ? 'Đăng nhập'
                              : 'Lưu'}
                    </Button>
                </DialogFooter>
            </DialogContent>
        </Dialog>
    );
}
