<?php

declare(strict_types=1);

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;

/**
 * One Facebook account signed in on the Messenger bridge. Holds no cookie or token: only the bridge login id and what the bridge reports.
 *
 * @property int $id
 * @property int $integration_id
 * @property string $login_id
 * @property string|null $remote_id
 * @property string|null $name
 * @property string|null $avatar_path path on the private `local` disk, generated by the server
 * @property string|null $avatar_mxc the `mxc://` URI the stored picture came from
 * @property string $status `connected|error|disconnected`
 * @property list<string>|null $permissions scopes ticked for this account; null = defaults
 * @property string|null $last_error
 * @property string|null $bridge_state
 * @property Carbon|null $bridge_state_at
 * @property Carbon|null $connected_at
 */
class MessengerAccount extends Model
{
    public const PERMISSIONS = ['receive', 'reply', 'proactive'];

    // * An account without stored scopes keeps the old channel defaults: `proactive` off (unofficial channel), the others on.
    public const DEFAULT_PERMISSIONS = ['receive', 'reply'];

    protected $fillable = [
        'integration_id',
        'login_id',
        'remote_id',
        'name',
        'avatar_path',
        'avatar_mxc',
        'status',
        'permissions',
        'last_error',
        'bridge_state',
        'bridge_state_at',
        'connected_at',
    ];

    protected $casts = [
        'permissions' => 'array',
        'bridge_state_at' => 'datetime',
        'connected_at' => 'datetime',
    ];

    /** @return BelongsTo<Integration, $this> */
    public function integration(): BelongsTo
    {
        return $this->belongsTo(Integration::class);
    }

    /** @return HasMany<Conversation, $this> */
    public function conversations(): HasMany
    {
        return $this->hasMany(Conversation::class);
    }

    /** @return list<string> */
    public function effectivePermissions(): array
    {
        return is_array($this->permissions) ? array_values($this->permissions) : self::DEFAULT_PERMISSIONS;
    }

    public function allows(string $permission): bool
    {
        return in_array($permission, $this->effectivePermissions(), true);
    }

    /** * The id behind this account's ghost user (`@meta_<id>:domain`). */
    public function ghostRemoteId(): string
    {
        return $this->remote_id !== null && $this->remote_id !== '' ? $this->remote_id : $this->login_id;
    }
}
