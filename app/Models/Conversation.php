<?php

declare(strict_types=1);

namespace App\Models;

use App\Concerns\QueryBuilder;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;

/**
 * @property string $id UUID v7
 * @property int|null $integration_id
 * @property int|null $messenger_account_id
 * @property int|null $zalo_account_id
 * @property int $account_scope part of the unique key: the Zalo account id (0 on other channels)
 * @property string $provider
 * @property string $external_chat_id
 * @property string $type `private|group`
 * @property string $title
 * @property string|null $username
 * @property string|null $last_message_preview
 * @property string|null $last_message_direction `in|out`
 * @property Carbon|null $last_message_at
 * @property int $unread_count
 * @property string|null $avatar_path path on the private `local` disk, generated by the server
 * @property string|null $avatar_mxc the `mxc://` URI the stored picture came from
 * @property Carbon|null $pinned_at global pin; set means the conversation is listed first
 */
class Conversation extends Model
{
    use HasUuids;
    use QueryBuilder;

    // * Read by `AuthorizeResource`: `conversations.view` reads, `conversations.reply` sends.
    public const PERMISSION_RESOURCE = 'conversations';

    // * Read by `ItemController::defaultSearchFields()`.
    public const SEARCH_FIELDS = ['title', 'username'];

    public const TYPE_PRIVATE = 'private';

    public const TYPE_GROUP = 'group';

    public const TYPE_LABELS = [
        self::TYPE_PRIVATE => 'Cá nhân',
        self::TYPE_GROUP => 'Nhóm',
    ];

    protected $fillable = [
        'integration_id',
        'messenger_account_id',
        'zalo_account_id',
        'account_scope',
        'provider',
        'external_chat_id',
        'type',
        'title',
        'username',
        'last_message_preview',
        'last_message_direction',
        'last_message_at',
        'unread_count',
        'avatar_path',
        'avatar_mxc',
    ];

    protected $casts = [
        'last_message_at' => 'datetime',
        'pinned_at' => 'datetime',
        'unread_count' => 'integer',
    ];

    /** @return BelongsTo<Integration, $this> */
    public function integration(): BelongsTo
    {
        return $this->belongsTo(Integration::class);
    }

    /** @return BelongsTo<ZaloAccount, $this> */
    public function zaloAccount(): BelongsTo
    {
        return $this->belongsTo(ZaloAccount::class);
    }

    /** @return BelongsTo<MessengerAccount, $this> */
    public function messengerAccount(): BelongsTo
    {
        return $this->belongsTo(MessengerAccount::class);
    }

    /** @return HasMany<ChatMessage, $this> */
    public function messages(): HasMany
    {
        return $this->hasMany(ChatMessage::class);
    }

    /**
     * * Chat is never created from the generic items API: conversations only come from the provider.
     *
     * @return array<string, array<int, string>>
     */
    public static function rules(mixed $ignoring = null): array
    {
        return [
            'title' => ['sometimes', 'string', 'max:255'],
        ];
    }
}
